def menu():
        level = 1
        day = 1
        mood = 50
        losses = 0
        wins = 0
        print("Welcome Trainer")
        while True:
            ask = input("What Would You Like To Do Today?(Train or Nothing or Battle)") #Ask The User For What They Would Like To Do
            print(f"Day {day}")
            print(f"Mood {mood}")
            day = day + 1 #Days Go By
            if ask == "Train": #Training Boosts Level
                if level <= 9:
                     charmander()
                elif level >= 20: #After 20 Days Of Training, They Level Up
                     print("Congrats, Your Charmeleon Has Evolved Into Charizard")
                     charizard()
                elif level >= 10: #After 10 Days Of Training, They Level Up
                     print("Congrats, Your Charmander Has Evolved Into Charmeleon")
                     charmeleon()
                print(f"Level {level}")
                level = level + 1
            if ask == "Nothing":
                 break
            if ask == "Battle":
                battle = input("Gym Battle Or Final Boss Battle?")
                if battle == "Gym Battle":
                    outcome = random.randint(1,10) #70-30 Odds For Winning Gym Battles
                    if outcome >= 8:
                         print("You Have Loss Your Gym Battle")
                         level = level + 0
                         mood = mood - 1 #Losses Means A Decrease In Mood
                         losses = losses + 1 #Losses Contribute To Record
                         print(f"Mood {mood}")
                         print(f"Record: {wins} - {losses}")
                    if outcome <= 7: #70-30 Odds For Winning Gym Battles
                         print("You Have Won Your Gym Battle")
                         level = level + 2
                         mood = mood + 1
                         wins = wins + 1 #Wins Contribute To Record
                         print(f"Mood {mood}") #Prints Mood
                         print(f"Record: {wins} - {losses}") #Prints Record For Both Wins And Losses
                if battle == "Final Boss Battle":
                     odds = 50 - level #Odds For Winning Are Based On The Player's Level
                     if odds >= 41:
                         product = random.randint(1,10)
                         if product >= 5: #If Level Is 1, Then The Odds Are 40/60
                            print ("You Have Lost The Final Boss Battle")
                            mood = mood - 5
                            losses = losses + 1
                            print(f"Mood {mood}")
                            print(f"Record: {wins} - {losses}")
                            break
                         if product <= 4: #If Level Is 1, Then The Odds Are 40/60
                            print ("You Have Won The Final Boss Battle")
                            mood = mood + 5
                            wins = wins + 1
                            print(f"Mood {mood}")
                            print(f"Record: {wins} - {losses}")
                     elif odds >= 31:
                         product = random.randint(1,10)
                         if product >= 6: #If Level Is 2, Then The Odds Are 50/50
                            print ("You Have Lost The Final Boss Battle")
                            losses = losses + 1
                            mood = mood - 5
                            print(f"Mood {mood}")
                            print(f"Record: {wins} - {losses}")
                            break
                         if product <= 5: #If Level Is 2, Then The Odds Are 50/50
                            print ("You Have Won The Final Boss Battle")
                            mood = mood + 5
                            wins = wins + 1
                            print(f"Mood {mood}")
                            print(f"Record: {wins} - {losses}")
                     else:
                         product = random.randint(1,10)
                         if product >= 7: #If Level Is 3, Then The Odds Are 60/40
                            print ("You Have Lost The Final Boss Battle")
                            mood = mood - 5
                            losses = losses + 1
                            print(f"Mood {mood}")
                            print(f"Record: {wins} - {losses}")
                            break
                         if product <= 6: #If Level Is 3, Then The Odds Are 60/40
                            print ("You Have Won The Final Boss Battle")
                            mood = mood + 5
                            wins = wins + 1
                            print(f"Mood {mood}")
                            print(f"Record: {wins} - {losses}")

menu()
